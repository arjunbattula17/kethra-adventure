// Writes a 1024-pixel copy beside every texture file over 1024 pixels that the game can fetch
// (public/textures/*/ and public/models/*/Textures/), named <name>.1k.<ext>, and the list of them in
// src/core/textures1k.ts. On Performance the game shrinks those maps to 1024 anyway
// (textureCache.ts, maxTextureSize); with the copies it downloads a quarter of the bytes for the
// same picture.
//
//   node tools/make-1k-textures.mjs
//
// Resized in headless Chrome (high-quality smoothing), so the project needs no native image
// dependency. JPEGs are written at quality 0.92; PNGs stay PNG (alpha). Re-run after replacing a map.
import { chromium } from 'playwright';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const PUBLIC = 'public';
const roots = [join(PUBLIC, 'textures'), ...readdirSync(join(PUBLIC, 'models')).map((d) => join(PUBLIC, 'models', d, 'Textures'))].filter((d) => existsSync(d));

function size(path) {
  const b = readFileSync(path);
  if (b[0] === 0x89) return [b.readUInt32BE(16), b.readUInt32BE(20)];
  let i = 2;
  while (i + 9 < b.length) {
    if (b[i] !== 0xff) return null;
    const m = b[i + 1];
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    i += 2 + b.readUInt16BE(i + 2);
  }
  return null;
}

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(png|jpe?g)$/i.test(name) && !/\.1k\./.test(name)) {
      const s = size(p);
      if (s && Math.max(...s) > 1024) files.push({ path: p, w: s[0], h: s[1] });
    }
  }
};
roots.forEach(walk);

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage();
const list = [];
let before = 0;
let after = 0;
for (const f of files) {
  const ext = extname(f.path).toLowerCase();
  const png = ext === '.png';
  const scale = 1024 / Math.max(f.w, f.h);
  const w = Math.round(f.w * scale);
  const h = Math.round(f.h * scale);
  const src = `data:image/${png ? 'png' : 'jpeg'};base64,${readFileSync(f.path).toString('base64')}`;
  const out = await page.evaluate(
    async ({ src, w, h, png }) => {
      // colorSpaceConversion 'none' and premultiplyAlpha 'none' keep data maps (normals, roughness)
      // as stored, the way the game decodes them.
      const blob = await (await fetch(src)).blob();
      const bmp = await createImageBitmap(blob, { colorSpaceConversion: 'none', premultiplyAlpha: 'none', resizeWidth: w, resizeHeight: h, resizeQuality: 'high' });
      const canvas = new OffscreenCanvas(w, h);
      canvas.getContext('2d').drawImage(bmp, 0, 0);
      const outBlob = await canvas.convertToBlob(png ? { type: 'image/png' } : { type: 'image/jpeg', quality: 0.92 });
      const bytes = new Uint8Array(await outBlob.arrayBuffer());
      let s = '';
      for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
      return btoa(s);
    },
    { src, w, h, png },
  );
  const dest = f.path.slice(0, -ext.length) + '.1k' + ext;
  const data = Buffer.from(out, 'base64');
  // Tiny flat masks compress better at full size; a copy that saves under half the bytes isn't worth a file.
  if (data.length > statSync(f.path).size / 2) {
    if (existsSync(dest)) unlinkSync(dest);
    continue;
  }
  writeFileSync(dest, data);
  before += statSync(f.path).size;
  after += data.length;
  list.push(relative(PUBLIC, f.path).replaceAll('\\', '/'));
  console.log(`${relative(PUBLIC, f.path)}  ${(statSync(f.path).size / 1048576).toFixed(2)} -> ${(data.length / 1048576).toFixed(2)} MB`);
}
await browser.close();
list.sort();
const entries = list.map((p) => `  '${p}',\n`).join('');
writeFileSync('src/core/textures1k.ts', `// Generated by tools/make-1k-textures.mjs: the texture files (under public/) with a 1024-pixel .1k copy.\nexport const TEXTURES_1K: readonly string[] = [\n${entries}];\n`);
console.log(`${list.length} files: ${(before / 1048576).toFixed(1)} MB -> ${(after / 1048576).toFixed(1)} MB`);
